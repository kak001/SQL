-- SELECT
-- SELECT es un statement para extraer datos de una base de datos (consultar)
-- de forma que su sintaxis es SELECT en mayuscula como palabra reservada de SQL

SELECT * FROM users;
-- Selecciona toda la tabla de users y la muestra en consola

SELECT name FROM users;
-- Selecciona la columan name y la muestra en consola

SELECT id, name FROM users;
-- Selecciona la columna id y name de la tabla users y la muestra en consola